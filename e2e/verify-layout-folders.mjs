import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    const file = (name, text) => ({ kind: 'file', name, getFile: async () => new File([text], name), isSameEntry: async other => other.name === name });
    const folder = (name, children) => ({ kind: 'directory', name, async *values() { yield* children; } });
    const docs = folder('测试文稿', [file('初见.md', '# 初见\n\n文件夹里的文稿'), file('ignore.png', 'not markdown'), folder('子文件夹', [file('子文稿.md', '# 子文稿')])]);
    window.showDirectoryPicker = async () => { if (window.cancelFolder) throw new DOMException('Cancelled', 'AbortError'); return docs; };
  });
  await page.goto('http://127.0.0.1:1420/');
  const menu = async (group, item, checked = false) => { await page.getByRole('button', { name: group, exact: true }).click(); await page.getByRole(checked ? 'menuitemcheckbox' : 'menuitem', { name: item, exact: true }).click(); };
  await expect(page.locator('.sidebar')).toHaveCount(0);
  await expect(page.locator('.topbar .brand')).toContainText('Chartelis');
  for (const name of ['设置', '文件', '编辑', '视图', '帮助']) await expect(page.locator('.topbar').getByRole('button', { name, exact: true })).toBeVisible();
  for (const width of [1280, 720, 640]) {
    await page.setViewportSize({ width, height: 900 });
    const bounds = await page.locator('.topbar').evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth, height: el.getBoundingClientRect().height }));
    expect(bounds.height).toBe(48); expect(bounds.scroll).toBeLessThanOrEqual(bounds.width);
  }
  await page.screenshot({ path: 'artifacts/topbar-compact-640.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.keyboard.press('Control+n');
  const rich = page.getByRole('textbox', { name: 'Markdown 编辑器', exact: true });
  await rich.click(); await page.keyboard.type('abc');
  await menu('帮助', '字符表');
  await page.getByRole('textbox', { name: '搜索字符' }).fill('U+00A9');
  await expect(page.getByRole('button', { name: '版权 ©', exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: '搜索字符' }).fill('无穷');
  await page.getByRole('button', { name: '无穷 ∞', exact: true }).click();
  await page.screenshot({ path: 'artifacts/character-sheet.png', animations: 'disabled' });
  await page.getByRole('button', { name: '插入', exact: true }).click();
  await expect(rich).toHaveText('abc∞'); await expect(rich).toBeFocused();
  await page.getByRole('button', { name: '撤销', exact: true }).click(); await expect(rich).toHaveText('abc');
  await menu('视图', '只读模式', true); await menu('帮助', '字符表');
  await expect(page.getByRole('button', { name: '插入', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '关闭对话框' }).click(); await menu('视图', '只读模式', true);
  await menu('文件', '打开文件夹…');
  await expect(page.locator('.sidebar')).toBeVisible();
  const folder = page.getByRole('navigation', { name: '文件夹中的文稿' });
  await expect(folder).toContainText('初见.md'); await expect(folder).not.toContainText('ignore.png');
  await folder.getByRole('button', { name: '初见.md', exact: true }).click(); await expect(rich).toContainText('文件夹里的文稿');
  await rich.click(); await page.keyboard.press('Control+End'); await page.keyboard.type(' draft');
  await page.getByRole('button', { name: '刷新文件夹', exact: true }).click();
  await folder.getByRole('button', { name: '初见.md', exact: true }).click(); await expect(rich).toContainText('draft');
  await folder.getByRole('button', { name: '子文件夹', exact: true }).click();
  await folder.getByRole('button', { name: '子文稿.md', exact: true }).click(); await expect(rich).toHaveText('子文稿');
  await page.getByRole('button', { name: '返回上一级', exact: true }).click();
  await page.screenshot({ path: 'artifacts/topbar-folder-layout.png', animations: 'disabled' });
  await page.evaluate(() => { window.cancelFolder = true; });
  await menu('文件', '打开文件夹…'); await expect(folder).toContainText('初见.md');
  await menu('视图', '显示状态栏', true); await expect(page.getByRole('button', { name: '展开底栏', exact: true })).toBeVisible();
  await menu('视图', '显示顶栏', true); await expect(page.getByRole('button', { name: '展开顶栏', exact: true })).toBeVisible();
  await expect(page.locator('.app-menu-panel')).toHaveCount(0);
  await page.screenshot({ path: 'artifacts/hidden-bars.png', animations: 'disabled' });
  await page.reload();
  await expect(page.locator('.topbar')).toBeHidden(); await expect(page.locator('.statusbar')).toBeHidden();
  await page.getByRole('button', { name: '展开顶栏', exact: true }).click();
  await page.getByRole('button', { name: '展开底栏', exact: true }).click();
  await expect(page.locator('.topbar')).toBeVisible(); await expect(page.locator('.statusbar')).toBeVisible();
  await expect(page.locator('.sidebar')).toHaveCount(0);
  await page.keyboard.press('Control+p'); await page.getByRole('dialog', { name: '已打开的文稿' }).getByRole('button', { name: /初见.md/ }).click();
  await expect(rich).toContainText('draft');
  await menu('文件', '打开文件夹…'); await menu('文件', '关闭文件夹'); await expect(page.locator('.sidebar')).toHaveCount(0);
  await expect(rich).toContainText('draft');
  expect(errors).toEqual([]);
  console.log('PASS: compact menus, character insert/undo/read-only, folder browse/refresh/cancel, draft preservation, floating bar restore + persistence, quick document switch.');
} finally { await browser.close(); }
