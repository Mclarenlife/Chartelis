import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 960 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:1420/');
  await page.getByRole('button', { name: '设置', exact: true }).click();
  const preview = page.getByRole('toolbar', { name: '选区工具栏预览' });
  await preview.scrollIntoViewIfNeeded();
  const palette = page.getByRole('group', { name: '可选工具' });
  await palette.getByRole('button', { name: '高亮', exact: true }).click();
  await page.getByRole('button', { name: '向左移动所选工具' }).click();
  const order = await preview.getByRole('button').evaluateAll(buttons => buttons.map(button => button.dataset.format));
  assert.deepEqual(order, ['bold', 'italic', 'strike', 'inlineCode', 'h2', 'highlight', 'quote']);
  await page.screenshot({ path: 'artifacts/toolbar-settings.png', animations: 'disabled' });
  await page.getByRole('button', { name: '关闭对话框' }).click();
  await page.keyboard.press('Control+n');
  const editor = page.getByRole('textbox', { name: 'Markdown 编辑器', exact: true });
  await editor.click();
  await page.keyboard.type('Toolbar selection test');
  await page.keyboard.press('Shift+Home');
  const live = page.getByRole('toolbar', { name: '文字格式', exact: true });
  await expect(live).toBeVisible();
  assert.deepEqual(await live.getByRole('button').evaluateAll(buttons => buttons.map(button => button.dataset.format)), order);
  await live.getByRole('button', { name: '粗体', exact: true }).click();
  await expect(editor.locator('strong')).toHaveText('Toolbar selection test');
  await page.screenshot({ path: 'artifacts/toolbar-live.png', animations: 'disabled' });
  await editor.click({ button: 'right' });
  const menu = page.getByRole('menu', { name: 'Markdown 格式', exact: true });
  await expect(menu).toBeVisible();
  await expect(menu.getByRole('menuitem')).toHaveCount(23);
  assert((await menu.getByRole('menuitem').allTextContents()).every(text => !text.trim()));
  await page.keyboard.press('ArrowRight');
  await expect(menu.getByRole('menuitem', { name: '斜体', exact: true })).toBeFocused();
  await page.keyboard.press('ArrowDown');
  await expect(menu.getByRole('menuitem', { name: '一级标题', exact: true })).toBeFocused();
  await page.screenshot({ path: 'artifacts/toolbar-context.png', animations: 'disabled' });
  await menu.getByRole('menuitem', { name: '高亮', exact: true }).click();
  await expect(editor.locator('mark')).toHaveText('Toolbar selection test');
  await expect(page.locator('.topbar').getByRole('button', { name: '导出文稿', exact: true })).toHaveCount(1);
  await expect(page.locator('.topbar').getByRole('button', { name: '另存为', exact: true })).toHaveCount(0);
  await page.locator('.topbar').getByRole('button', { name: '导出文稿', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '导出文稿', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '关闭对话框' }).click();
  await page.getByRole('button', { name: '视图', exact: true }).click();
  await page.getByRole('menuitemcheckbox', { name: '显示顶栏', exact: true }).click();
  await expect(page.locator('.topbar')).toBeHidden();
  await page.reload();
  await expect(page.locator('.topbar')).toBeHidden();
  await expect(page.getByRole('textbox', { name: 'Markdown 编辑器', exact: true })).toContainText('Toolbar selection test');
  await page.getByRole('button', { name: '视图', exact: true }).click();
  await page.getByRole('menuitemcheckbox', { name: '显示顶栏', exact: true }).click();
  await expect(page.locator('.topbar')).toBeVisible();
  assert.deepEqual(errors, []);
  console.log('PASS: preview matches live toolbar, order persists, formatting preserves selection, context grid keyboard navigation, export button, persisted topbar visibility.');
} finally { await browser.close(); }
