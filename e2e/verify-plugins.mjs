import { chromium, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:1420/');
  const settings = () => page.getByRole('button', { name: '设置', exact: true }).click();
  const close = () => page.getByRole('button', { name: '关闭对话框' }).click();
  const menu = async (name, item) => { await page.getByRole('button', { name, exact: true }).click(); await page.getByRole('menuitem', { name: item, exact: true }).click(); };
  const command = async label => { await menu('编辑', '插件选区命令'); await page.getByRole('menuitem', { name: `${label} · 写作工具箱`, exact: true }).click(); };
  await settings();
  await page.getByRole('button', { name: '查看示例插件' }).click();
  await expect(page.getByLabel('插件安装预览')).toContainText('会议纪要');
  await page.getByRole('button', { name: '安装插件', exact: true }).click();
  await expect(page.getByRole('switch', { name: '启用 写作工具箱' })).toBeChecked();
  await page.getByRole('button', { name: '石墨', exact: true }).click();
  await expect(page.locator('html')).toHaveCSS('--paper', '#25272b');
  await expect(page.getByRole('button', { name: '导入插件包' })).toHaveCSS('background-color', 'rgb(37, 39, 43)');
  await page.getByRole('heading', { name: '插件管理' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/plugins-settings.png', animations: 'disabled' });
  await close();
  await menu('文件', '从模板新建');
  await page.getByRole('menuitem', { name: '会议纪要 · 写作工具箱' }).click();
  const rich = page.getByRole('textbox', { name: 'Markdown 编辑器', exact: true });
  await expect(rich).toContainText('议题');
  await expect(page.locator('.save-state')).toHaveText('尚未保存');
  await page.reload();
  await expect(rich).toContainText('议题');
  await expect(page.locator('html')).toHaveCSS('--paper', '#25272b');
  await page.keyboard.press('Control+n');
  await rich.click(); await page.keyboard.type('hello world'); await page.keyboard.press('Shift+Home');
  await command('转为大写');
  await expect(rich).toHaveText('HELLO WORLD');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(rich).toHaveText('hello world');
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await expect(rich).toHaveText('HELLO WORLD');
  await rich.click(); await page.keyboard.press('End'); await page.keyboard.type('!');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(rich).toHaveText('HELLO WORLD');
  await page.getByRole('button', { name: '切换为 Markdown 源码' }).click();
  const source = page.getByRole('textbox', { name: 'Markdown 源码编辑器', exact: true });
  await source.click(); await page.keyboard.press('Control+Home'); await page.keyboard.press('Control+Shift+End');
  await command('转为小写'); await expect(source).toContainText('hello world');
  await page.getByRole('button', { name: '撤销', exact: true }).click(); await expect(source).toContainText('HELLO WORLD');
  await page.getByRole('button', { name: '重做', exact: true }).click(); await expect(source).toContainText('hello world');
  await page.getByRole('button', { name: '视图', exact: true }).click();
  await page.getByRole('menuitemcheckbox', { name: '只读模式', exact: true }).click();
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: '插件选区命令', exact: true })).toBeDisabled();
  await page.keyboard.press('Escape');
  await settings();
  await page.getByRole('switch', { name: '启用 写作工具箱' }).click();
  await expect(page.locator('html')).not.toHaveCSS('--paper', '#25272b');
  await expect(page.getByRole('button', { name: '跟随系统', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.reload(); await settings();
  await expect(page.getByRole('switch', { name: '启用 写作工具箱' })).not.toBeChecked();
  const example = JSON.parse(readFileSync('examples/plugins/writing-kit.chartelis-plugin.json', 'utf8'));
  const file = page.getByLabel('选择插件包');
  await file.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...example, script: 'alert(1)' })) });
  await expect(page.getByRole('alert')).toContainText('不支持的插件字段');
  await file.setInputFiles({ name: 'update.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...example, version: '1.1.0' })) });
  await expect(page.getByLabel('插件安装预览')).toContainText('将替换已安装');
  await page.getByRole('button', { name: '替换此插件' }).click();
  await expect(page.getByRole('switch', { name: '启用 写作工具箱' })).not.toBeChecked();
  await expect(page.locator('.plugin-card')).toContainText('v1.1.0');
  await close();
  await page.getByRole('button', { name: '文件', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: '从模板新建', exact: true })).toBeDisabled();
  await page.keyboard.press('Escape'); await settings();
  await page.getByRole('switch', { name: '启用 写作工具箱' }).click();
  await page.getByRole('button', { name: '卸载 写作工具箱' }).click();
  await page.getByRole('button', { name: '确认卸载' }).click();
  await expect(page.locator('.plugin-card')).toHaveCount(0);
  await close();
  await page.keyboard.press('Control+p');
  await expect(page.getByRole('dialog', { name: '已打开的文稿' })).toContainText('会议纪要');
  await close();
  await page.reload(); await settings(); await expect(page.locator('.plugin-card')).toHaveCount(0);
  // Storage errors must not leave an apparently installed but non-persistent plugin.
  await page.evaluate(() => {
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) { if (key === 'chartelis.plugins.v1') throw new DOMException('Quota', 'QuotaExceededError'); return original.call(this, key, value); };
  });
  await page.getByRole('button', { name: '查看示例插件' }).click();
  await page.getByRole('button', { name: '安装插件', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('保存失败');
  await expect(page.locator('.plugin-card')).toHaveCount(0);
  await page.reload();
  await page.evaluate(() => localStorage.setItem('chartelis.plugins.v1', 'corrupt-test-record'));
  await page.reload(); await settings();
  await expect(page.getByRole('alert')).toContainText('原始记录未覆盖');
  expect(await page.evaluate(() => localStorage.getItem('chartelis.plugins.v1'))).toBe('corrupt-test-record');
  await page.getByRole('button', { name: '重置插件记录', exact: true }).click();
  await page.getByRole('button', { name: '确认重置', exact: true }).click();
  await expect(page.getByRole('button', { name: '导入插件包', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
  console.log('PASS: install, theme, template draft/recovery, rich/source commands + undo/redo, read-only, disable/restart, invalid import, explicit update, uninstall preserves documents.');
} finally { await browser.close(); }
