import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 1100, height: 800 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:1420');
  const sidebarToggle = page.locator('.sidebar-toggle');
  await expect(sidebarToggle).toBeDisabled();
  await expect(sidebarToggle).not.toHaveAttribute('title');
  const idleStyle = await sidebarToggle.evaluate(el => {
    const style = getComputedStyle(el);
    return [style.backgroundColor, style.color, style.opacity];
  });
  const toggleBox = await sidebarToggle.boundingBox();
  await page.mouse.move(toggleBox.x + 10, toggleBox.y + 10);
  expect(await sidebarToggle.evaluate(el => {
    const style = getComputedStyle(el);
    return [style.backgroundColor, style.color, style.opacity];
  })).toEqual(idleStyle);
  await expect(sidebarToggle).toHaveCSS('pointer-events', 'none');
  await expect(sidebarToggle).toHaveCSS('cursor', 'default');
  await page.keyboard.press('Control+n');
  await page.getByRole('button', { name: '切换为 Markdown 源码' }).click();
  const source = page.getByRole('textbox', { name: 'Markdown 源码编辑器' });
  await source.fill('# 覆盖式顶栏\n\n' + Array.from({ length: 40 }, (_, i) => `段落 ${i}：文字从透明渐变顶栏下方经过，保持连续的阅读空间。`).join('\n\n'));
  await page.getByRole('button', { name: '切换为即时预览' }).click();
  const scroller = page.locator('.document-session:not([hidden]) > .writing-scroll:not([hidden])');
  expect((await scroller.boundingBox()).y).toBe(0);
  await expect(page.locator('.topbar')).toHaveCSS('position', 'absolute');
  const background = await page.locator('.topbar').evaluate(el => getComputedStyle(el).backgroundImage);
  expect(background).toContain('linear-gradient'); expect(background).toContain('100%');
  const heading = page.getByRole('textbox', { name: 'Markdown 编辑器', exact: true }).locator('h1');
  const before = (await heading.boundingBox()).y;
  await scroller.evaluate((el, top) => { el.scrollTop = top - 16; }, before);
  expect((await heading.boundingBox()).y).toBeLessThan(64);
  expect((await heading.boundingBox()).y).toBeGreaterThanOrEqual(0);
  await page.screenshot({ path: 'artifacts/header-overlay-light.png' });
  await page.getByRole('button', { name: '切换深色主题' }).click();
  await page.screenshot({ path: 'artifacts/header-overlay-dark.png' });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '设置', exact: true })).toBeVisible();
  const widthSetting = page.getByRole('slider', { name: '正文最大宽度' });
  await expect(widthSetting).toHaveValue('960');
  await widthSetting.fill('1400');
  await page.getByRole('button', { name: '关闭对话框' }).click();
  await page.setViewportSize({ width: 1800, height: 800 });
  const article = page.locator('.document-session:not([hidden]) .writing-page');
  await expect(article).toHaveCSS('width', '1400px');
  await page.reload();
  await expect(article).toHaveCSS('width', '1400px');
  await page.setViewportSize({ width: 720, height: 800 });
  expect((await article.boundingBox()).width).toBeLessThan(720);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(720);
  await page.setViewportSize({ width: 1800, height: 800 });
  await page.screenshot({ path: 'artifacts/header-wide-content.png' });
  const exportWidth = await page.evaluate(async () => {
    const { capturePreview, createPreviewSurface } = await import('/src/preview-export.ts');
    const surface = createPreviewSurface(capturePreview('<p>Export width</p>', 'serif'));
    const width = surface.querySelector('article').getBoundingClientRect().width;
    surface.remove(); return width;
  });
  expect(exportWidth).toBe(1400);
  await page.keyboard.press('Control+f');
  expect((await page.locator('.document-search').boundingBox()).y).toBeGreaterThanOrEqual(64);
  await page.getByRole('button', { name: '关闭搜索' }).click();
  await page.getByRole('button', { name: 'AI 助手', exact: true }).click();
  expect((await page.locator('.ai-heading').boundingBox()).y).toBeGreaterThanOrEqual(64);
  await page.getByRole('button', { name: '关闭 AI 助手' }).click();
  await page.getByRole('button', { name: '切换为 Markdown 源码' }).click();
  expect((await scroller.boundingBox()).y).toBe(0);
  await scroller.evaluate(el => { el.scrollTop = 100; });
  expect(await scroller.evaluate(el => el.scrollTop)).toBe(100);
  await page.getByRole('button', { name: '收起顶栏' }).click();
  await expect(page.locator('.topbar')).toBeHidden();
  expect((await page.getByRole('button', { name: '展开顶栏' }).boundingBox()).x).toBeGreaterThan(1700);
  expect((await scroller.boundingBox()).y).toBe(0);
  const collapseBottom = page.getByRole('button', { name: '收起底栏' });
  expect((await collapseBottom.boundingBox()).x).toBeGreaterThan(1700);
  await collapseBottom.click();
  await expect(page.locator('.statusbar')).toBeHidden();
  expect((await page.getByRole('button', { name: '展开底栏' }).boundingBox()).x).toBeGreaterThan(1700);
  await page.reload();
  await expect(page.locator('.statusbar')).toBeHidden();
  await expect(page.locator('.topbar')).toBeHidden();
  await page.screenshot({ path: 'artifacts/right-restore-buttons.png' });
  await page.getByRole('button', { name: '展开底栏' }).click();
  await expect(page.locator('.statusbar')).toBeVisible();
  await page.getByRole('button', { name: '展开顶栏' }).click();
  await expect(page.locator('.topbar')).toBeVisible();
  expect(errors).toEqual([]);
  console.log('PASS: overlay gradient, configurable/persisted width, responsive and export widths, search/AI controls, source scrolling, collapse/restore.');
} finally { await browser.close(); }
